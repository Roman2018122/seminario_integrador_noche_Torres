# Operadores aritméticos en un taller mecánico

costo_reparacion = 10
cantidad_repuestos = 3

print(
    "Costo total:",
    costo_reparacion + cantidad_repuestos
)  # 13

print(
    "Diferencia de costos:",
    costo_reparacion - cantidad_repuestos
)  # 7

print(
    "Costo multiplicado:",
    costo_reparacion * cantidad_repuestos
)  # 30

print(
    "Costo dividido:",
    costo_reparacion / cantidad_repuestos
)  # 3.333...

print(
    "División entera:",
    costo_reparacion // cantidad_repuestos
)  # 3

print(
    "Residuo del cálculo:",
    costo_reparacion % cantidad_repuestos
)  # 1

print(
    "Potencia del costo:",
    costo_reparacion ** cantidad_repuestos
)  # 1000