print("Operadores de comparación en Taller Mecánico")

costo_reparacion = float(
    input("Ingrese el costo de la reparación: ")
)

costo_repuestos = float(
    input("Ingrese el costo de los repuestos: ")
)

print(
    costo_reparacion,
    "==",
    costo_repuestos,
    costo_reparacion == costo_repuestos
)

print(
    costo_reparacion,
    "!=",
    costo_repuestos,
    costo_reparacion != costo_repuestos
)

print(
    costo_reparacion,
    ">",
    costo_repuestos,
    costo_reparacion > costo_repuestos
)

print(
    costo_reparacion,
    "<",
    costo_repuestos,
    costo_reparacion < costo_repuestos
)

print(
    costo_reparacion,
    ">=",
    costo_repuestos,
    costo_reparacion >= costo_repuestos
)

print(
    costo_reparacion,
    "<=",
    costo_repuestos,
    costo_reparacion <= costo_repuestos
)